Q=[]
def q(n, chapter, title, kind, diff, freq, *payload):
    # payload should end with a list of follow-ups. Some compact entries intentionally
    # merge the key insight into the solution; normalize them here for a uniform layout.
    if not payload or not isinstance(payload[-1], list):
        raise ValueError(f'Q{n}: final payload must be follow-up list')
    followups = payload[-1]
    fields = list(payload[:-1])
    if len(fields) < 3:
        raise ValueError(f'Q{n}: insufficient fields: {fields}')
    prompt = fields[0]; intent = fields[1]; rem = fields[2:]
    if len(rem) >= 4:
        insight, solution, teaching, pitfalls = rem[:4]
    elif len(rem) == 3:
        insight = '先识别题目或情境中的核心结构，再选择最稳健、最适合教学的路径。'
        solution, teaching, pitfalls = rem
    elif len(rem) == 2:
        insight = '先从条件与目标中提炼可迁移的结构。'
        solution, teaching = rem; pitfalls = '只给结论、不解释关键动机，或遗漏边界与验证。'
    else:
        insight = '抓住核心结构。'; solution = rem[0]; teaching = rem[0]; pitfalls = '只给结论、不解释。'
    Q.append(dict(n=n,chapter=chapter,title=title,kind=kind,diff=diff,freq=freq,prompt=prompt,intent=intent,insight=insight,solution=solution,teaching=teaching,pitfalls=pitfalls,followups=followups))

