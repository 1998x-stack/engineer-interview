    rr=p.add_run(title); set_run_font(rr,'Noto Sans CJK SC',9.5,bold=True,color=title_color)
    for i,line in enumerate(body_lines):
        p=c.add_paragraph(style=None); set_para_spacing(p, after=2, line=1.25)
